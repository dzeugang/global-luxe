class Command(BaseCommand):
    help = 'Crée toutes les catégories et produits avec images réelles'

    def handle(self, *args, **options):
        self.stdout.write(self.style.SUCCESS('🚀 Démarrage du seed...'))

        total_categories = 0
        total_products = 0

        for cat_data in CATEGORIES_DATA:
            # Créer ou mettre à jour la catégorie
            category, created = Category.objects.update_or_create(
                slug=cat_data['slug'],
                defaults={
                    'name': cat_data['name'],
                    'image': cat_data['image'],
                    'order': cat_data['order'],
                    'is_active': True,
                }
            )

            status = '✨ Créée' if created else '♻️  Mise à jour'
            self.stdout.write(self.style.SUCCESS(
                f'{status} catégorie : {category.name}'
            ))
            total_categories += 1

            # Créer les produits
            for prod_data in cat_data['products']:
                product, p_created = Product.objects.update_or_create(
                    sku=prod_data['sku'],
                    defaults={
                        'name': prod_data['name'],
                        'description': prod_data['description'],
                        'main_image': prod_data['main_image'],
                        'images': [prod_data['main_image']],
                        'base_price': Decimal(str(prod_data['base_price'])),
                        'sale_price': Decimal(str(prod_data['sale_price'])),
                        'stock': prod_data['stock'],
                        'rating': Decimal(str(prod_data.get('rating', 0))),
                        'category': category,
                        'is_active': True,
                        'is_featured': prod_data.get('is_featured', False),
                        'is_best_seller': prod_data.get('is_best_seller', False),
                    }
                )

                p_status = '  ✅' if p_created else '  ♻️ '
                self.stdout.write(f'{p_status} {product.name} — {product.sale_price}€')
                total_products += 1

        self.stdout.write(self.style.SUCCESS(
            f'\n🎉 Terminé !'
            f'\n   📂 {total_categories} catégories'
            f'\n   📦 {total_products} produits'
        ))